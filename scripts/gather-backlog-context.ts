import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { collectTodos } from "./nightly-tasks/tasks/05-todo-report.js";

async function main(): Promise<void> {
  const root = process.cwd();
  const todos = await collectTodos(root);

  const backlogDir = join(root, "backlog");
  const backlogFiles = existsSync(backlogDir)
    ? readdirSync(backlogDir).filter((f) => f.endsWith(".md"))
    : [];

  const readyItems: Array<{ file: string; title: string }> = [];
  const doneItems: Array<{ file: string; title: string }> = [];

  for (const file of backlogFiles) {
    const content = readFileSync(join(backlogDir, file), "utf8");
    const isDone = /^status:\s*done\s*$/m.test(content);
    const titleMatch = /^#\s+(.+)$/m.exec(content);
    const title = titleMatch ? titleMatch[1] : file;

    if (isDone) {
      doneItems.push({ file, title });
    } else {
      readyItems.push({ file, title });
    }
  }

  const lines: string[] = [
    "# DevKit Codebase Diagnostics for Backlog Planning",
    "",
    "> Auto-generated by scripts/gather-backlog-context.ts. Use this context to plan real, concrete engineering work.",
    "",
    "## Current Backlog Summary",
    "",
    `- Ready items (${readyItems.length}):`,
    ...readyItems.map((item) => `  - \`${item.file}\`: ${item.title}`),
    `- Completed items (${doneItems.length}):`,
    ...doneItems.map((item) => `  - \`${item.file}\`: ${item.title}`),
    "",
    "## Outstanding Code Markers (TODO / FIXME / HACK)",
    "",
  ];

  if (todos.length === 0) {
    lines.push("No TODO/FIXME markers found in tracked code.", "");
  } else {
    lines.push("| File | Line | Kind | Note |");
    lines.push("| --- | --- | --- | --- |");
    for (const todo of todos) {
      lines.push(`| \`${todo.file}\` | ${todo.line} | ${todo.kind} | ${todo.text} |`);
    }
    lines.push("");
  }

  lines.push(
    "## Recommended Focus Areas",
    "",
    "1. `@buzludeniz/devkit-core`: Configuration loaders, result handlers, plugin lifecycles, and shared process utilities.",
    "2. `@buzludeniz/devkit-cli`: Flags (`--json`, `--force`, `--dry-run`), new productivity commands, and robust input validation.",
    "3. Quality & Edge Cases: Timeout handling, flaky test hardening, and informative error messages.",
    "",
  );

  const outPath = join(root, ".nightly", "DIAGNOSTICS.md");
  writeFileSync(outPath, lines.join("\n"), "utf8");
  console.log(
    `Wrote diagnostics to ${outPath} (${readyItems.length} ready, ${doneItems.length} done, ${todos.length} todos)`,
  );
}

main().catch((err) => {
  console.error("Failed to gather backlog context:", err);
  process.exitCode = 1;
});
