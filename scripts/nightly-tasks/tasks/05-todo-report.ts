import { join, relative } from "node:path";
import { writeIfChanged } from "../lib/fs.js";
import { commitAll } from "../lib/git.js";
import { listFiles, readTextFile, repoRoot } from "../lib/repo.js";
import { BaseTask } from "../task-base.js";

export interface TodoEntry {
	file: string;
	line: number;
	kind: "TODO" | "FIXME" | "HACK";
	text: string;
}

const TODO_PATTERN = /\b(TODO|FIXME|HACK)\b:?\s*(.*)$/;

export async function collectTodos(root: string): Promise<TodoEntry[]> {
	const files = await listFiles(
		root,
		(file) => file.endsWith(".ts") || file.endsWith(".md"),
	);

	const entries: TodoEntry[] = [];

	for (const file of files) {
		const content = await readTextFile(file).catch(() => "");
		const lines = content.split(/\r?\n/);

		lines.forEach((text, index) => {
			const match = TODO_PATTERN.exec(text);
			if (!match) {
				return;
			}

			entries.push({
				file: relative(root, file).split("\\").join("/"),
				line: index + 1,
				kind: match[1] as TodoEntry["kind"],
				text: match[2]?.trim() || "(no description)",
			});
		});
	}

	return entries.sort(
		(a, b) =>
			a.file.localeCompare(b.file) ||
			a.line - b.line ||
			a.kind.localeCompare(b.kind),
	);
}

export async function buildTodoReport(root: string): Promise<string> {
	const entries = await collectTodos(root);
	const lines: string[] = [
		"# Outstanding work",
		"",
		"> Generated by the nightly maintenance workflow. Do not edit by hand.",
		"",
		`Found ${entries.length} TODO, FIXME and HACK marker${
			entries.length === 1 ? "" : "s"
		}.`,
		"",
	];

	if (entries.length === 0) {
		lines.push("The codebase has no outstanding markers.", "");
		return lines.join("\n");
	}

	for (const kind of ["TODO", "FIXME", "HACK"] as const) {
		const matching = entries.filter((entry) => entry.kind === kind);
		if (matching.length === 0) {
			continue;
		}

		lines.push(`## ${kind}`, "");
		lines.push("| File | Line | Note |");
		lines.push("| --- | --- | --- |");

		for (const entry of matching) {
			lines.push(`| \`${entry.file}\` | ${entry.line} | ${entry.text} |`);
		}

		lines.push("");
	}

	return lines.join("\n");
}

export class TodoReportTask extends BaseTask {
	readonly name = "todo-report";
	readonly description = "Regenerate docs/project/todos.md from code comments";

	protected async execute(): Promise<string> {
		const content = await buildTodoReport(repoRoot);
		const changed = await writeIfChanged(
			join(repoRoot, "docs/project/todos.md"),
			content,
		);

		if (!changed) {
			return "no changes";
		}

		await commitAll("docs: refresh outstanding work report", repoRoot);
		return "updated docs/project/todos.md";
	}
}
