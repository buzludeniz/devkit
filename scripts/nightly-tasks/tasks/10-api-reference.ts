import { join, relative } from "node:path";
import { writeIfChanged } from "../lib/fs.js";
import { commitAll } from "../lib/git.js";
import {
	listFiles,
	listWorkspacePackages,
	readTextFile,
	repoRoot,
	toPosix,
} from "../lib/repo.js";
import { ReportTask } from "../task-base.js";

export interface ExportedSymbol {
	file: string;
	kind: string;
	name: string;
}

const EXPORT_PATTERN =
	/^export\s+(?:abstract\s+)?(?:async\s+)?(function|class|interface|type|const|enum)\s+([A-Za-z0-9_]+)/gm;

export function extractExports(
	content: string,
	file: string,
): ExportedSymbol[] {
	const symbols: ExportedSymbol[] = [];

	EXPORT_PATTERN.lastIndex = 0;
	let match: RegExpExecArray | null = EXPORT_PATTERN.exec(content);

	while (match !== null) {
		symbols.push({
			file,
			kind: match[1] ?? "unknown",
			name: match[2] ?? "unknown",
		});
		match = EXPORT_PATTERN.exec(content);
	}

	return symbols;
}

export async function collectExports(
	root: string,
): Promise<Array<{ packageName: string; symbols: ExportedSymbol[] }>> {
	const packages = await listWorkspacePackages(root);
	const files = await listFiles(
		root,
		(file) => file.endsWith(".ts") && !file.endsWith(".test.ts"),
	);

	const grouped: Array<{ packageName: string; symbols: ExportedSymbol[] }> = [];

	for (const workspacePackage of packages) {
		const prefix = `${workspacePackage.directory}/src/`;
		const packageFiles = files.filter((file) => toPosix(file).includes(prefix));
		const symbols: ExportedSymbol[] = [];

		for (const file of packageFiles) {
			const content = await readTextFile(file).catch(() => "");
			symbols.push(
				...extractExports(content, relative(root, file).split("\\").join("/")),
			);
		}

		grouped.push({ packageName: workspacePackage.name, symbols });
	}

	return grouped;
}

export async function buildApiReference(root: string): Promise<string> {
	const grouped = await collectExports(root);
	const lines: string[] = [
		"# API reference",
		"",
		"> Generated by the nightly maintenance workflow. Do not edit by hand.",
		"",
		"Every symbol exported from the workspace packages, grouped by package.",
		"",
	];

	for (const { packageName, symbols } of grouped) {
		lines.push(`## ${packageName}`, "");

		if (symbols.length === 0) {
			lines.push("No exported symbols found.", "");
			continue;
		}

		lines.push("| Symbol | Kind | Defined in |");
		lines.push("| --- | --- | --- |");

		for (const symbol of symbols) {
			lines.push(
				`| \`${symbol.name}\` | ${symbol.kind} | \`${symbol.file}\` |`,
			);
		}

		lines.push("");
	}

	return lines.join("\n");
}

export class ApiReferenceTask extends ReportTask {
	readonly name = "api-reference";
	readonly description =
		"Regenerate docs/reference/api.md from exported symbols";
	readonly reportPath = "docs/reference/api.md";
	readonly commitMessage = "docs: refresh API reference";

	protected async buildReport(): Promise<string> {
		return buildApiReference(repoRoot);
	}
}
