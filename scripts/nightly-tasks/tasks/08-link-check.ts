import { access } from "node:fs/promises";
import { dirname, extname, join, relative, resolve } from "node:path";
import { listFiles, readTextFile } from "../lib/repo.js";
import { ReportTask } from "../task-base.js";

export interface BrokenLink {
  file: string;
  line: number;
  link: string;
}

const LINK_PATTERN = /\[[^\]]*\]\(([^)]+)\)/g;

function normaliseLink(rawLink: string): string | null {
  const link = rawLink.trim().split(/\s+/)[0] ?? "";
  if (link.length === 0) {
    return null;
  }
  if (/^(?:https?:|mailto:|tel:|#)/.test(link)) {
    return null;
  }
  return link.split("#")[0] ?? null;
}

async function exists(filePath: string): Promise<boolean> {
  return access(filePath).then(
    () => true,
    () => false,
  );
}

/**
 * Resolves a link against a base directory, trying the extension-less
 * VitePress form (`/plugins`) as well as plain files and directory indexes.
 */
async function resolvesToFile(base: string, target: string): Promise<boolean> {
  const direct = resolve(base, target);
  const candidates = [direct];

  if (extname(target) === "") {
    candidates.push(`${direct}.md`, resolve(direct, "index.md"), resolve(direct, "README.md"));
  }

  for (const candidate of candidates) {
    if (await exists(candidate)) {
      return true;
    }
  }

  return false;
}

async function linkResolves(root: string, file: string, target: string): Promise<boolean> {
  if (target.startsWith("/")) {
    // Site-root links are written from the VitePress docs root, not from the
    // repository root.
    if (await resolvesToFile(join(root, "docs"), `.${target}`)) {
      return true;
    }
    return resolvesToFile(root, `.${target}`);
  }

  return resolvesToFile(dirname(file), target);
}

export async function findBrokenLinks(root: string): Promise<BrokenLink[]> {
  const markdownFiles = await listFiles(root, (file) => /\.mdx?$/i.test(file));
  const broken: BrokenLink[] = [];

  for (const file of markdownFiles) {
    const content = await readTextFile(file).catch(() => "");
    const lines = content.split(/\r?\n/);
    const relativePath = relative(root, file).split("\\").join("/");
    let inFence = false;

    for (const [index, line] of lines.entries()) {
      if (line.trimStart().startsWith("```")) {
        inFence = !inFence;
        continue;
      }
      if (inFence) {
        continue;
      }

      // Inline code is documentation about links, not a link itself.
      const searchable = line.replace(/`[^`]*`/g, "");
      LINK_PATTERN.lastIndex = 0;
      let match: RegExpExecArray | null = LINK_PATTERN.exec(searchable);

      while (match !== null) {
        const target = normaliseLink(match[1] ?? "");
        if (target !== null && !(await linkResolves(root, file, target))) {
          broken.push({
            file: relativePath,
            line: index + 1,
            link: target,
          });
        }

        match = LINK_PATTERN.exec(searchable);
      }
    }
  }

  return broken;
}

export async function buildLinkReport(root: string): Promise<string> {
  const markdownFiles = await listFiles(root, (file) => /\.mdx?$/i.test(file));
  const broken = await findBrokenLinks(root);

  const lines: string[] = [
    "# Link report",
    "",
    "> Generated by the nightly maintenance workflow. Do not edit by hand.",
    "",
    `Scanned ${markdownFiles.length} Markdown file${markdownFiles.length === 1 ? "" : "s"}.`,
    "",
  ];

  if (broken.length === 0) {
    lines.push("All relative links resolve to existing files.", "");
    return lines.join("\n");
  }

  lines.push(`Found ${broken.length} broken relative link${broken.length === 1 ? "" : "s"}.`, "");
  lines.push("| File | Line | Target |");
  lines.push("| --- | --- | --- |");

  for (const entry of broken) {
    lines.push(`| \`${entry.file}\` | ${entry.line} | \`${entry.link}\` |`);
  }

  lines.push("");
  return lines.join("\n");
}

export class LinkCheckTask extends ReportTask {
  readonly name = "link-check";
  readonly description = "Regenerate docs/project/link-report.md for Markdown links";
  readonly reportPath = "docs/project/link-report.md";
  readonly commitMessage = "docs: refresh Markdown link report";

  protected async buildReport(): Promise<string> {
    return buildLinkReport(this.root);
  }
}
