import { access } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { writeIfChanged } from "../lib/fs.js";
import { commitAll } from "../lib/git.js";
import { listFiles, readTextFile } from "../lib/repo.js";
import { ReportTask } from "../task-base.js";

export interface BrokenLink {
	file: string;
	line: number;
	link: string;
}

const LINK_PATTERN = /\[[^\]]*\]\(([^)]+)\)/g;

function normaliseLink(rawLink: string): string | null {
	const link = rawLink.trim().split(/\s+/)[0] ?? "";
	if (link.length === 0) {
		return null;
	}
	if (/^(?:https?:|mailto:|tel:|#)/.test(link)) {
		return null;
	}
	return link.split("#")[0] ?? null;
}

export async function findBrokenLinks(root: string): Promise<BrokenLink[]> {
	const markdownFiles = await listFiles(root, (file) => /\.mdx?$/i.test(file));
	const broken: BrokenLink[] = [];

	for (const file of markdownFiles) {
		const content = await readTextFile(file).catch(() => "");
		const lines = content.split(/\r?\n/);

		for (const [index, line] of lines.entries()) {
			LINK_PATTERN.lastIndex = 0;
			let match: RegExpExecArray | null = LINK_PATTERN.exec(line);

			while (match !== null) {
				const target = normaliseLink(match[1] ?? "");
				if (target !== null) {
					const resolved = target.startsWith("/")
						? resolve(root, `.${target}`)
						: resolve(dirname(file), target);

					const exists = await access(resolved).then(
						() => true,
						() => false,
					);

					if (!exists) {
						broken.push({
							file: file
								.slice(root.length + 1)
								.split("\\")
								.join("/"),
							line: index + 1,
							link: target,
						});
					}
				}

				match = LINK_PATTERN.exec(line);
			}
		}
	}

	return broken;
}

export async function buildLinkReport(root: string): Promise<string> {
	const markdownFiles = await listFiles(root, (file) => /\.mdx?$/i.test(file));
	const broken = await findBrokenLinks(root);

	const lines: string[] = [
		"# Link report",
		"",
		"> Generated by the nightly maintenance workflow. Do not edit by hand.",
		"",
		`Scanned ${markdownFiles.length} Markdown file${
			markdownFiles.length === 1 ? "" : "s"
		}.`,
		"",
	];

	if (broken.length === 0) {
		lines.push("All relative links resolve to existing files.", "");
		return lines.join("\n");
	}

	lines.push(
		`Found ${broken.length} broken relative link${broken.length === 1 ? "" : "s"}.`,
		"",
	);
	lines.push("| File | Line | Target |");
	lines.push("| --- | --- | --- |");

	for (const entry of broken) {
		lines.push(`| \`${entry.file}\` | ${entry.line} | \`${entry.link}\` |`);
	}

	lines.push("");
	return lines.join("\n");
}

export class LinkCheckTask extends ReportTask {
	readonly name = "link-check";
	readonly description =
		"Regenerate docs/project/link-report.md for Markdown links";
	readonly reportPath = "docs/project/link-report.md";
	readonly commitMessage = "docs: refresh Markdown link report";

	protected async buildReport(): Promise<string> {
		return buildLinkReport(this.root);
	}
}
