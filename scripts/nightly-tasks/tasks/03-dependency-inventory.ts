import { readFile } from "node:fs/promises";
import { join } from "node:path";
import { writeIfChanged } from "../lib/fs.js";
import { commitAll } from "../lib/git.js";
import { listWorkspacePackages, repoRoot } from "../lib/repo.js";
import { BaseTask } from "../task-base.js";

type DependencyField = "dependencies" | "devDependencies" | "peerDependencies";

const FIELDS: DependencyField[] = [
	"dependencies",
	"devDependencies",
	"peerDependencies",
];

function dependencyEntries(
	manifest: Record<string, unknown>,
	field: DependencyField,
): Array<[string, string]> {
	const value = manifest[field];
	if (typeof value !== "object" || value === null) {
		return [];
	}
	return Object.entries(value as Record<string, string>).sort(([a], [b]) =>
		a.localeCompare(b),
	);
}

export async function buildDependencyInventory(root: string): Promise<string> {
	const packages = await listWorkspacePackages(root);
	const rootManifest = await readFile(join(root, "package.json"), "utf8");
	const rootPackage = JSON.parse(rootManifest) as Record<string, unknown>;

	const lines: string[] = [
		"# Dependency inventory",
		"",
		"> Generated by the nightly maintenance workflow. Do not edit by hand.",
		"",
		"This report lists every dependency declared by the workspace so that",
		"version drift and unexpected packages are easy to spot in review.",
		"",
	];

	const allManifests: Array<{
		name: string;
		manifest: Record<string, unknown>;
	}> = [
		{
			name: `${String(rootPackage.name ?? "root")} (workspace root)`,
			manifest: rootPackage,
		},
		...packages.map((workspacePackage) => ({
			name: workspacePackage.name,
			manifest: workspacePackage.manifest,
		})),
	];

	let total = 0;

	for (const { name, manifest } of allManifests) {
		lines.push(`## ${name}`, "");

		let packageTotal = 0;

		for (const field of FIELDS) {
			const entries = dependencyEntries(manifest, field);
			if (entries.length === 0) {
				continue;
			}

			lines.push(`### ${field}`, "");
			lines.push("| Package | Version |");
			lines.push("| --- | --- |");

			for (const [dependency, version] of entries) {
				lines.push(`| \`${dependency}\` | \`${version}\` |`);
				packageTotal += 1;
			}

			lines.push("");
		}

		if (packageTotal === 0) {
			lines.push("No dependencies declared.", "");
		}

		total += packageTotal;
	}

	lines.push("## Summary", "");
	lines.push(`- Manifests scanned: ${allManifests.length}`);
	lines.push(`- Declared dependencies: ${total}`);
	lines.push("");

	return lines.join("\n");
}

export class DependencyInventoryTask extends BaseTask {
	readonly name = "dependency-inventory";
	readonly description =
		"Regenerate docs/security/dependencies.md from every manifest";

	protected async execute(): Promise<string> {
		const content = await buildDependencyInventory(repoRoot);
		const changed = await writeIfChanged(
			join(repoRoot, "docs/security/dependencies.md"),
			content,
		);

		if (!changed) {
			return "no changes";
		}

		await commitAll("docs: refresh dependency inventory", repoRoot);
		return "updated docs/security/dependencies.md";
	}
}
