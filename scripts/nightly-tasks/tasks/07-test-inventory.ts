import { join, relative } from "node:path";
import { writeIfChanged } from "../lib/fs.js";
import { commitAll } from "../lib/git.js";
import {
	countLines,
	listFiles,
	listWorkspacePackages,
	readTextFile,
	toPosix,
} from "../lib/repo.js";
import { ReportTask } from "../task-base.js";

interface PackageTestStats {
	name: string;
	testFiles: number;
	testCases: number;
	sourceFiles: number;
	sourceLines: number;
}

function countTestCases(content: string): number {
	return (content.match(/\b(?:it|test)\s*\(/g) ?? []).length;
}

export async function collectTestStats(
	root: string,
): Promise<PackageTestStats[]> {
	const packages = await listWorkspacePackages(root);
	const files = await listFiles(root, (file) => file.endsWith(".ts"));

	const stats: PackageTestStats[] = [];

	for (const workspacePackage of packages) {
		const prefix = `${workspacePackage.directory}/`;
		const packageFiles = files.filter((file) => toPosix(file).includes(prefix));
		const testFiles = packageFiles.filter((file) => file.endsWith(".test.ts"));
		const sourceFiles = packageFiles.filter(
			(file) => !file.endsWith(".test.ts"),
		);

		let testCases = 0;
		for (const file of testFiles) {
			const content = await readTextFile(file).catch(() => "");
			testCases += countTestCases(content);
		}

		let sourceLines = 0;
		for (const file of sourceFiles) {
			const content = await readTextFile(file).catch(() => "");
			sourceLines += countLines(content);
		}

		stats.push({
			name: workspacePackage.name,
			testFiles: testFiles.length,
			testCases,
			sourceFiles: sourceFiles.length,
			sourceLines,
		});
	}

	return stats;
}

export async function buildTestInventory(root: string): Promise<string> {
	const stats = await collectTestStats(root);
	const totalTests = stats.reduce((sum, entry) => sum + entry.testCases, 0);
	const totalFiles = stats.reduce((sum, entry) => sum + entry.testFiles, 0);

	const lines: string[] = [
		"# Test inventory",
		"",
		"> Generated by the nightly maintenance workflow. Do not edit by hand.",
		"",
		`- Test files: ${totalFiles}`,
		`- Test cases: ${totalTests}`,
		"",
		"| Package | Test files | Test cases | Source files | Source lines |",
		"| --- | --- | --- | --- | --- |",
	];

	for (const entry of stats) {
		lines.push(
			`| \`${entry.name}\` | ${entry.testFiles} | ${entry.testCases} | ${entry.sourceFiles} | ${entry.sourceLines} |`,
		);
	}

	lines.push("", "## Test files", "");

	const testFiles = await listFiles(root, (file) => file.endsWith(".test.ts"));

	for (const file of testFiles) {
		lines.push(`- \`${relative(root, file).split("\\").join("/")}\``);
	}

	lines.push("");
	return lines.join("\n");
}

export class TestInventoryTask extends ReportTask {
	readonly name = "test-inventory";
	readonly description =
		"Regenerate docs/metrics/tests.md with test coverage inventory";
	readonly reportPath = "docs/metrics/tests.md";
	readonly commitMessage = "docs: refresh test inventory";

	protected async buildReport(): Promise<string> {
		return buildTestInventory(this.root);
	}
}
