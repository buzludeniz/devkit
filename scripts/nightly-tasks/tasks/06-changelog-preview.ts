import { git } from "../lib/git.js";
import { ReportTask } from "../task-base.js";

export interface CommitEntry {
  hash: string;
  subject: string;
  type: string;
}

const TYPE_PATTERN = /^(\w+)(?:\([^)]*\))?!?:/;

export function parseCommitLog(output: string): CommitEntry[] {
  return output
    .split(/\r?\n/)
    .filter((line) => line.trim().length > 0)
    .map((line) => {
      const [hash, ...rest] = line.split("|");
      const subject = rest.join("|").trim();
      const match = TYPE_PATTERN.exec(subject);
      return {
        hash: hash.trim(),
        subject,
        type: match ? match[1].toLowerCase() : "other",
      };
    });
}

export async function buildChangelogPreview(root: string, limit = 100): Promise<string> {
  const output = await git(["log", `-${limit}`, "--pretty=format:%h|%s"], root);
  const commits = parseCommitLog(output);
  const types = [
    "feat",
    "fix",
    "perf",
    "refactor",
    "docs",
    "test",
    "build",
    "ci",
    "chore",
    "other",
  ];

  const lines: string[] = [
    "# Recent changes",
    "",
    "> Generated by the nightly maintenance workflow. Do not edit by hand.",
    "",
    `The ${commits.length} most recent commits, grouped by conventional type.`,
    "",
  ];

  for (const type of types) {
    const matching = commits.filter((commit) => commit.type === type);
    if (matching.length === 0) {
      continue;
    }

    lines.push(`## ${type}`, "");
    for (const commit of matching) {
      lines.push(`- \`${commit.hash}\` ${commit.subject}`);
    }
    lines.push("");
  }

  return lines.join("\n");
}

export class ChangelogPreviewTask extends ReportTask {
  readonly name = "changelog-preview";
  readonly description = "Regenerate docs/changelog-preview.md from recent commits";
  readonly reportPath = "docs/changelog-preview.md";
  readonly commitMessage = "docs: refresh recent changes preview";

  protected async buildReport(): Promise<string> {
    return buildChangelogPreview(this.root);
  }
}
