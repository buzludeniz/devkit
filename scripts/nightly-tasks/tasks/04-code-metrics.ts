import { join, relative } from "node:path";
import { writeIfChanged } from "../lib/fs.js";
import { commitAll } from "../lib/git.js";
import {
	countLines,
	listFiles,
	listWorkspacePackages,
	readTextFile,
	repoRoot,
	toPosix,
} from "../lib/repo.js";
import { BaseTask } from "../task-base.js";

interface FileMetric {
	path: string;
	lines: number;
}

export interface CodeMetrics {
	files: FileMetric[];
	totalLines: number;
	largest: FileMetric[];
}

export async function collectCodeMetrics(root: string): Promise<CodeMetrics> {
	const packages = await listWorkspacePackages(root);
	const packageDirectories = packages.map(
		(workspacePackage) => `${workspacePackage.directory}/`,
	);

	const candidates = await listFiles(
		root,
		(file) => file.endsWith(".ts") && !file.endsWith(".test.ts"),
	);

	const files: FileMetric[] = [];

	for (const file of candidates) {
		const posix = toPosix(file);
		if (!packageDirectories.some((directory) => posix.includes(directory))) {
			continue;
		}

		const content = await readTextFile(file).catch(() => "");
		files.push({
			path: relative(root, file).split("\\").join("/"),
			lines: countLines(content),
		});
	}

	files.sort((a, b) => b.lines - a.lines || a.path.localeCompare(b.path));

	return {
		files,
		totalLines: files.reduce((sum, file) => sum + file.lines, 0),
		largest: files.slice(0, 10),
	};
}

export async function buildCodeMetricsDoc(root: string): Promise<string> {
	const metrics = await collectCodeMetrics(root);
	const lines: string[] = [
		"# Code metrics",
		"",
		"> Generated by the nightly maintenance workflow. Do not edit by hand.",
		"",
		`- Source files: ${metrics.files.length}`,
		`- Total source lines: ${metrics.totalLines}`,
		`- Average file size: ${
			metrics.files.length === 0
				? 0
				: Math.round(metrics.totalLines / metrics.files.length)
		} lines`,
		"",
		"## Largest files",
		"",
		"| File | Lines |",
		"| --- | --- |",
	];

	for (const file of metrics.largest) {
		lines.push(`| \`${file.path}\` | ${file.lines} |`);
	}

	lines.push("", "## All source files", "");
	lines.push("| File | Lines |");
	lines.push("| --- | --- |");

	for (const file of metrics.files) {
		lines.push(`| \`${file.path}\` | ${file.lines} |`);
	}

	lines.push("");
	return lines.join("\n");
}

export class CodeMetricsTask extends BaseTask {
	readonly name = "code-metrics";
	readonly description = "Regenerate docs/metrics/code-size.md with file sizes";

	protected async execute(): Promise<string> {
		const content = await buildCodeMetricsDoc(repoRoot);
		const changed = await writeIfChanged(
			join(repoRoot, "docs/metrics/code-size.md"),
			content,
		);

		if (!changed) {
			return "no changes";
		}

		await commitAll("docs: refresh code size metrics", repoRoot);
		return "updated docs/metrics/code-size.md";
	}
}
