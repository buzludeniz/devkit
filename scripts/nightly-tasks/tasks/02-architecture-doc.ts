function dependencyNames(
	manifest: Record<string, unknown>,
	field: string,
): string[] {
	const value = manifest[field];
	if (typeof value !== "object" || value === null) {
		return [];
	}
	return Object.keys(value as Record<string, string>).sort();
}

export async function buildArchitectureDoc(root: string): Promise<string> {
	const packages = await listWorkspacePackages(root);
	const lines: string[] = [
		"# Architecture",
		"",
		"> Generated by the nightly maintenance workflow. Do not edit by hand.",
		"",
		"This repository is a pnpm workspace. The diagram below shows how the",
		"published packages depend on each other.",
		"",
		"```mermaid",
		"graph TD",
	];

	const known = new Set(
		packages.map((workspacePackage) => workspacePackage.name),
	);

	for (const workspacePackage of packages) {
		const dependencies = dependencyNames(
			workspacePackage.manifest,
			"dependencies",
		).filter((name) => known.has(name));

		for (const dependency of dependencies) {
			lines.push(
				`  ${workspacePackage.name.replace(/[^a-zA-Z0-9]/g, "_")}["${workspacePackage.name}"] --> ${dependency.replace(/[^a-zA-Z0-9]/g, "_")}["${dependency}"]`,
			);
		}
	}

	lines.push("```", "", "## Packages", "");
	lines.push("| Package | Version | Responsibility |");
	lines.push("| --- | --- | --- |");

	for (const workspacePackage of packages) {
		lines.push(
			`| \`${workspacePackage.name}\` | ${workspacePackage.version} | ${workspacePackage.description || "—"} |`,
		);
	}

	lines.push("", "## Workspace dependencies", "");

	for (const workspacePackage of packages) {
		const dependencies = dependencyNames(
			workspacePackage.manifest,
			"dependencies",
		);
		lines.push(
			`- **${workspacePackage.name}**: ${
				dependencies.length > 0
					? dependencies.join(", ")
					: "no runtime dependencies"
			}`,
		);
	}

	lines.push("");
	return lines.join("\n");
}

export class ArchitectureDocTask extends ReportTask {
	readonly name = "architecture-doc";
	readonly description =
		"Regenerate docs/architecture.md from the workspace manifests";
	readonly reportPath = "docs/architecture.md";
	readonly commitMessage = "docs: regenerate architecture overview";

	protected async buildReport(): Promise<string> {
		return buildArchitectureDoc(repoRoot);
	}
}
