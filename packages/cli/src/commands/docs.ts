import { mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join, relative } from "node:path";
import { Command } from "commander";

export interface DocEntry {
  /** Exported symbol name. */
  name: string;
  /** `function`, `class`, `interface`, `type`, `const` or `enum`. */
  kind: string;
  /** Cleaned JSDoc description, or an empty string when none was written. */
  description: string;
  /** Source file relative to the scanned root. */
  file: string;
}

const EXPORT_PATTERN =
  /\/\*\*([\s\S]*?)\*\/\s*export\s+(?:abstract\s+)?(?:async\s+)?(function|class|interface|type|const|enum)\s+([A-Za-z0-9_]+)/g;

const IGNORED_DIRECTORIES = new Set(["node_modules", "dist", "coverage", ".git", ".vitepress"]);

function cleanDescription(block: string): string {
  return block
    .split(/\r?\n/)
    .map((line) => line.trim().replace(/^\*\s?/, ""))
    .filter((line) => line.length > 0)
    .join(" ")
    .trim();
}

/**
 * Extracts documented exports from a single TypeScript source file.
 *
 * Only exports immediately preceded by a `/** ... *\/` block are included; the
 * generated page is meant to describe the public surface, not every symbol.
 */
export function extractDocEntries(source: string, file: string): DocEntry[] {
  const entries: DocEntry[] = [];

  for (const match of source.matchAll(EXPORT_PATTERN)) {
    entries.push({
      name: match[3],
      kind: match[2],
      description: cleanDescription(match[1]),
      file,
    });
  }

  return entries;
}

async function collectSourceFiles(root: string): Promise<string[]> {
  const found: string[] = [];

  async function walk(directory: string): Promise<void> {
    const entries = await readdir(directory, { withFileTypes: true });

    for (const entry of entries) {
      if (entry.isDirectory()) {
        if (!IGNORED_DIRECTORIES.has(entry.name)) {
          await walk(join(directory, entry.name));
        }
        continue;
      }

      if (
        entry.isFile() &&
        entry.name.endsWith(".ts") &&
        !entry.name.endsWith(".test.ts") &&
        !entry.name.endsWith(".d.ts")
      ) {
        found.push(join(directory, entry.name));
      }
    }
  }

  await walk(root);
  return found.sort();
}

export async function generateDocs(root: string): Promise<DocEntry[]> {
  const files = await collectSourceFiles(root);
  const entries: DocEntry[] = [];

  for (const file of files) {
    const source = await readFile(file, "utf8");
    entries.push(...extractDocEntries(source, relative(root, file)));
  }

  return entries.sort((a, b) => a.file.localeCompare(b.file) || a.name.localeCompare(b.name));
}

export function renderDocs(entries: DocEntry[]): string {
  const lines = ["# Generated API documentation", ""];
  lines.push("Generated by `devkit docs:generate` from documented exports.", "");

  if (entries.length === 0) {
    lines.push("No documented exports were found.", "");
    return lines.join("\n");
  }

  let currentFile = "";

  for (const entry of entries) {
    if (entry.file !== currentFile) {
      currentFile = entry.file;
      lines.push(`## ${currentFile}`, "");
    }

    lines.push(`### \`${entry.name}\` (${entry.kind})`, "");
    lines.push(entry.description.length > 0 ? entry.description : "No description.", "");
  }

  return lines.join("\n");
}

export async function writeDocs(root: string, outputPath: string): Promise<number> {
  const entries = await generateDocs(root);
  await mkdir(dirname(outputPath), { recursive: true });
  await writeFile(outputPath, renderDocs(entries), "utf8");
  return entries.length;
}

export function docsGenerateCommand(): Command {
  return new Command("docs:generate")
    .description("Generate Markdown API documentation from documented exports")
    .option("-s, --source <dir>", "directory to scan", ".")
    .option("-o, --output <file>", "output Markdown file", "docs/generated/api.md")
    .action(async (options: { source: string; output: string }) => {
      const count = await writeDocs(options.source, options.output);
      console.log(`Documented ${count} exports in ${options.output}`);
    });
}
